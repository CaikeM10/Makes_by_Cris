// Offline generator: never connects to a database or reads credentials.
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
function load(file) {
  const module = { exports: {} };
  const source = ts.transpileModule(fs.readFileSync(path.join(root, file), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
  vm.runInNewContext(source, { module, exports: module.exports, require: () => ({}) });
  return module.exports;
}
const { categories } = load('lib/data/categories.ts');
const { products, giftProducts } = load('lib/data/products.ts');
const gifts = new Set(giftProducts.map(p => p.id));
const quote = value => value === null ? 'null' : typeof value === 'boolean' || typeof value === 'number' ? String(value) : Array.isArray(value) ? `ARRAY[${value.map(quote).join(',')}]::text[]` : "'" + String(value).replace(/'/g, "''") + "'";
function insert(table, rows) {
  const keys = Object.keys(rows[0]);
  return `insert into public.${table} (${keys.join(', ')}) values\n${rows.map(row => '(' + keys.map(k => quote(row[k])).join(', ') + ')').join(',\n')}\non conflict (id) do nothing;\n`;
}
const rows = products.map((p, index) => ({ id: p.id, name: p.name, slug: p.slug, short_description: p.shortDescription, description: p.description, price: p.price, credit_price: p.creditPrice, image: p.image, category_id: categories.find(c => c.slug === p.category)?.id ?? (() => { throw Error('Categoria ausente'); })(), brand: p.brand, keywords: p.keywords, variations: p.variations ?? null, featured: p.featured, best_seller: p.bestSeller, gift_section: gifts.has(p.id), available: p.available, active: p.active, catalog_order: index, created_at: p.createdAt + 'T00:00:00Z' }));
const sql = '-- Generated by node scripts/generate-catalog-seed.cjs. Development/staging only.\n-- Existing IDs are never overwritten; rerunning preserves administrative edits.\nbegin;\n' + insert('categories', categories.map((c, index) => ({ ...c, position: index }))) + insert('products', rows) + 'commit;\n';
fs.mkdirSync(path.join(root, 'supabase/seeds'), { recursive: true });
fs.writeFileSync(path.join(root, 'supabase/seeds/catalog.sql'), sql);
console.log(`Seed gerado: ${categories.length} categorias, ${products.length} produtos.`);
